/** '... WHERE a = ? AND b = ?' -> '... WHERE a = $1 AND b = $2'. No SQL string literal
 * in this codebase contains a '?', so a plain global replace is safe. */
function toPgPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${(index += 1)}`);
}

/**
 * A SQLite-driver-shaped statement bound to `executor` (the pool or one checked-out
 * client). get/all/run are async; run() mirrors the old {changes, lastInsertRowid}
 * result — every table has an `id` identity PK, so INSERTs without a RETURNING clause
 * get ` RETURNING id` appended to feed lastInsertRowid.
 */
function prepareOn(executor, sql) {
  const text = toPgPlaceholders(sql);
  const runText =
    /^\s*INSERT\b/i.test(sql) && !/\bRETURNING\b/i.test(sql) ? `${text} RETURNING id` : text;
  return {
    async get(...params) {
      const result = await executor.query(text, params);
      return result.rows[0];
    },
    async all(...params) {
      const result = await executor.query(text, params);
      return result.rows;
    },
    async run(...params) {
      const result = await executor.query(runText, params);
      return { changes: result.rowCount, lastInsertRowid: result.rows[0]?.id };
    },
  };
}

export const db = {
  /** Statement shim over the pool. `?` placeholders, like the old SQLite API. */
  prepare(sql) {
    return prepareOn(pool, sql);
  },

  /**
   * Run `work(tx)` inside one transaction on one checked-out client. tx exposes
   * get/all/run taking (sql, ...params). COMMIT on success, ROLLBACK on throw. A failed
   * statement aborts the whole Postgres transaction, so retries (booking codes) must
   * wrap the transaction, never sit inside it.
   */
  async withTransaction(work) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const tx = {
        get: (sql, ...params) => prepareOn(client, sql).get(...params),
        all: (sql, ...params) => prepareOn(client, sql).all(...params),
        run: (sql, ...params) => prepareOn(client, sql).run(...params),
      };
      const result = await work(tx);
      await client.query('COMMIT');
      client.release();
      return result;
    } catch (error) {
      // The original error always propagates; ROLLBACK's own outcome only decides
      // whether the client goes back to the pool (rolled back fine, connection is
      // healthy) or gets destroyed (ROLLBACK failed, connection presumed dead).
      let rolledBack = false;
      try {
        await client.query('ROLLBACK');
        rolledBack = true;
      } catch {
        // Fall through with rolledBack = false.
      }
      if (rolledBack) {
        client.release();
      } else {
        client.release(error);
      }
      throw error;
    }
  },
};

