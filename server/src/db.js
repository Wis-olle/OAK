// Backfills salons that predate per-weekday hours: the legacy whole-week pair becomes
// seven identical rows, which partners then refine day by day from the console. Runs
// after the seed, so on a fresh database the seeded salons are covered on the first
// boot rather than the second. ON CONFLICT because two instances booting at the same
// moment both pass the NOT EXISTS before either one inserts.
await pool.query(`
  INSERT INTO salon_hours (salon_id, weekday, "start", "end", is_off)
  SELECT s.id, d.weekday, s.open_time, s.close_time, 0
  FROM salons s, (VALUES (0),(1),(2),(3),(4),(5),(6)) AS d(weekday)
  WHERE s.open_time IS NOT NULL AND s.close_time IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM salon_hours h WHERE h.salon_id = s.id)
  ON CONFLICT (salon_id, weekday) DO NOTHING
`);

/* staff.rating stopped being a figure somebody typed into the console and became a cache of
   the real average of that technician's reviews. The writes that maintain it are the two
   RECOMPUTE_STAFF_RATING call sites: routes/reviews.js, where a review is written or edited,
   and routes/partner.js, where a reassignment carries one onto another roster row. The
   expression they run is defined in lib/staff-stats.js beside the live one, which computes
   the same average on read, so an endpoint serving both says whether the two have drifted
   rather than hiding it.

   This runs on every boot rather than once, and deliberately behind no sentinel: a cache
   that can only be repaired by a migration nobody will run again is a cache that stays
   wrong. The WHERE is what makes that free — on a converged database the UPDATE matches no
   row and writes nothing. Cast to real because that is what the column is: comparing it
   against the numeric the average comes back as widens both to float8, where 4.8 stored in
   four bytes is not 4.8 written in ten, and every roster row would look drifted forever.
   After the seed, for the reason the hours backfill above gives: a fresh database has to be
   right on its first boot rather than its second. And 0 keeps meaning "nobody has rated this
   person yet", which is what routes/partner.js filters its roster average on. */
await pool.query(`
  UPDATE staff st SET rating = COALESCE(
    (SELECT ROUND(AVG(r.rating), 1) FROM reviews r WHERE r.staff_id = st.id), 0
  )
  WHERE st.rating IS DISTINCT FROM COALESCE(
    (SELECT ROUND(AVG(r.rating), 1) FROM reviews r WHERE r.staff_id = st.id), 0
  )::real
`);

