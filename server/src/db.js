const { Pool, types } = pg;

// The old SQLite driver handed back plain JS numbers; keep that contract. int8 (COUNT,
// SUM of integers) and numeric (AVG, ROUND) otherwise arrive as strings.
types.setTypeParser(20, (value) => Number(value));
types.setTypeParser(1700, (value) => Number(value));

if (process.env.NODE_ENV === 'production' && !process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL must be set in production');
}

// Overridable so a test run can boot against a throwaway database instead of the dev one.
const connectionString =
  process.env.DATABASE_URL || 'postgres://postgres:postgres@localhost:5432/oak';

const host = new URL(connectionString).hostname;
const isLocalHost = host === 'localhost' || host === '127.0.0.1';

// max 5: hosted poolers (Supabase free tier) allow very few connections per client.
// TLS is required by those poolers but refused by the local Docker container.
const pool = new Pool({
  connectionString,
  max: 5,
  ssl: isLocalHost ? false : { rejectUnauthorized: false },
});

